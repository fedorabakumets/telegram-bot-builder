import type { EditorLearnTask } from './editor-learn-task';

/** Зона, которую подсвечивает шаг */
export type EditorLearnFocus = 'none' | 'palette' | 'canvas' | 'links' | 'properties';

/** Один шаг обучения редактора */
export interface EditorLearnStep {
  /** Идентификатор шага */
  id: string;
  /** Короткий заголовок в прогрессе */
  title: string;
  /** Текст проводника */
  text: string;
  /** Куда смотреть на этом шаге */
  focus: EditorLearnFocus;
  /** Узкий элемент внутри зоны, если подсвечивать нужно не всю панель */
  spotlight?: string;
  /** Действие, без которого «Далее» не включится */
  task: EditorLearnTask;
  /** Подсказка, пока действие не сделано */
  waitHint?: string;
  /** Кнопка, нажатие на которую засчитывает задание `click` */
  clickTarget?: string;
}

