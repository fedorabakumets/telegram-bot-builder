/** @fileoverview Общий контракт подтверждённой аналитики, диапазонов и полноты истории. */
/** Полнота истории выбранного окна; восстановленная первая дата не считается точной. */
export type AnalyticsV2HistoryStatus = 'complete' | 'partial' | 'unavailable';
/** Счётчики действий в личных или групповых чатах за период. */
export interface AnalyticsV2MessageScope {
  /** Входящие сообщения. */ incoming: number;
  /** Входящие сообщения, адресованные боту. */ incoming_to_bot: number;
  /** Отправленные ботом сообщения. */ outgoing: number;
  /** Подтверждённые нажатия с Telegram ID. */ callbacks: number;
  /** Проверенные записи старых нажатий без Telegram ID. */ historical_callbacks: number;
}
/** Счётчики известных типов чата; неизвестные и каналы входят только в общие значения. */
export interface AnalyticsV2ChatScopes {
  /** Личные чаты. */ private: AnalyticsV2MessageScope;
  /** Группы и супергруппы. */ group: AnalyticsV2MessageScope;
}
/** Нормализованный диапазон одного снимка. */
export interface AnalyticsV2Range {
  /** Включённая граница UTC. */
  from: string;
  /** Исключённая граница UTC. */
  to: string;
  /** Часовой пояс календарных интервалов и подписей. */
  timezone: string;
  /** Номинальный шаг ряда; календарный день при смене летнего времени может длиться 23 или 25 часов. */
  step_ms: number;
  /** Готовое окно либо явные даты. */
  period: string | null;
}
/** Итоги одного интервала: уникальные люди не суммируются по дням. */
export interface AnalyticsV2Summary {
  /** Подтверждённая аудитория; total_users относится ко всему времени. */
  audience: {
    /** Новые люди с известной первой датой. */ new_users: number;
    /** Люди с первым датированным свидетельством контакта в периоде; настоящее начало использования неизвестно. */ restored_users: number;
    /** Полнота первых дат для выбранного окна; при неполноте ноль new_users не доказывает отсутствие прихода. */ first_history_status: AnalyticsV2HistoryStatus;
    /** Подтверждённая аудитория за всё время. */ total_users: number;
    /** Уникальные люди с событием или аудированным свидетельством контакта в периоде. */ active_users: number;
    /** Контактировали в периоде и имеют более раннее сохранённое свидетельство контакта. */ returning_users: number;
    /** Люди с неизвестной датой начала использования. */ unknown_first_users: number;
  };
  /** Реальные сообщения, нажатия и служебные события. */
  messages: {
    /** Реальные входящие сообщения. */ incoming: number;
    /** Личные и подтверждённые направленные боту групповые сообщения. */ incoming_to_bot: number;
    /** Успешные отправки бота. */ outgoing: number;
    /** Реальные нажатия кнопок. */ callbacks: number;
    /** Проверенные записи старой истории без Telegram ID. */ historical_callbacks: number;
    /** Достоверно известные типы чата. */ chat_scopes: AnalyticsV2ChatScopes;
    /** Служебные события. */ system: number;
    /** Сумма входящих и ответов бота. */ total: number;
  };
  /** Группы с наблюдавшимися сообщениями и направленными действиями. */
  groups: {
    /** Группы с событиями в периоде. */ active_groups: number;
    /** Уникальные авторы наблюдаемой переписки. */ participants: number;
    /** Направленные действия с ботами. */ directed_actions: number;
  };
}
/** Одна временная точка. */
export interface AnalyticsV2Point {
  /** Стабильное начало интервала UTC; крайние значения ограничены выбранным окном. */
  date: string;
  /** Исключённый конец интервала UTC с учётом календарных границ; старые снимки могут не содержать его. */
  end_date?: string;
  /** Новые люди с известным первым взаимодействием. */
  new_users: number;
  /** Люди с первым датированным свидетельством контакта в интервале и недоказанной настоящей первой датой. */
  restored_users: number;
  /** Уникальные люди с событием или аудированным историческим свидетельством контакта. */
  active_users: number;
  /** Люди, уже использовавшие бота до текущего окна. */
  returning_users: number;
  /** Входящие сообщения. */
  incoming: number;
  /** Личные и подтверждённые направленные боту групповые сообщения. */
  incoming_to_bot: number;
  /** Успешные исходящие сообщения. */
  outgoing: number;
  /** Нажатия кнопок. */
  callbacks: number;
  /** Аудированные старые записи нажатий без Telegram ID. */
  historical_callbacks: number;
  /** Достоверно известные типы чата. */
  chat_scopes: AnalyticsV2ChatScopes;
  /** События состояния. */
  system: number;
  /** Группы с событиями внутри точки. */
  groups_active: number;
  /** Уникальные авторы групповых сообщений внутри точки. */
  group_participants: number;
  /** Направленные действия в группах внутри точки. */
  group_directed_actions: number;
}
/** Строка рейтинга без текстов переписки. */
export interface AnalyticsV2Leader {
  /** Telegram ID строкой без потери точности. */
  id: string;
  /** Уникальные люди с направленным контактом в группе, включая аудированную историю. */ people?: number;
  /** Человеческое название либо безопасный ID. */
  name: string;
  /** Публичный username при наличии. */
  username: string | null;
  /** Направленные сообщения либо наблюдаемая переписка в отдельном режиме. */
  messages: number;
  /** Нажатия кнопок. */
  callbacks: number;
  /** Сумма действий рейтинга. */
  total: number;
}
/** Источник подтверждённого привлечения. */
export interface AnalyticsV2Source {
  /** Стабильный ID источника либо статус неизвестного происхождения. */
  id: string;
  /** Название источника или объяснение статуса. */
  label: string;
  /** Новые пользователи с точной первой датой. */
  new_users: number;
  /** Первые сохранённые контакты с неизвестной фактической первой датой; не входят в точную стоимость привлечения. */ restored_users?: number;
  /** Уникальные вернувшиеся по ссылке люди. */
  returning_users: number;
  /** Все зарегистрированные входы. */
  starts: number;
}
/** Согласованный снимок всех зависимых карточек. */
export interface AnalyticsV2Snapshot {
  /** Версия определений метрик. */
  schema_version: 2;
  /** Подтверждённая аудитория каждого бота проекта за всё время для выбора области. */
  token_audiences?: Array<{
    /** ID бота в текущем проекте. */ token_id: number;
    /** Число людей с подтверждённым взаимодействием. */ total_users: number;
  }>;
  /** Проект с проверенным доступом. */
  project_id: number;
  /** Токен либо весь проект. */
  token_id: number | null;
  /** Общий момент получения снимка. */
  as_of: string;
  /** Последовательная версия состояния проекта. */
  revision: string;
  /** Нормализованное окно. */
  range: AnalyticsV2Range;
  /** Достоверность истории и начало покрытия каждого бота. */
  coverage: {
    /** Полнота событий выбранного окна. */ status: AnalyticsV2HistoryStatus;
    /** Начало общего подтверждённого покрытия. */ from: string | null;
    /** Ранее существовавшие люди без доказанной первой даты. */ legacy_unknown_users: number;
    /** Покрытие каждой сборки. */ bots: {
      /** Идентификатор бота. */ token_id: number;
      /** Начало новой записи либо отсутствие обновлённой сборки. */ from: string | null;
      /** Версия объявленных возможностей. */ version: number;
    }[];
    /** Понятное описание ограничений. */ description: string;
  };
  /** Итоги выбранного окна. */
  current: AnalyticsV2Summary;
  /** Итоги предыдущего равного окна; для всего времени отсутствуют. */
  previous: AnalyticsV2Summary | null;
  /** Общий временной ряд, до 500 точек. */
  points: AnalyticsV2Point[];
  /** Рейтинги направленного взаимодействия и отдельной наблюдаемой переписки. */
  leaders: {
    /** Люди по направленным действиям. */ users: AnalyticsV2Leader[];
    /** Группы по направленным действиям. */ groups: AnalyticsV2Leader[];
    /** Группы по наблюдаемым сообщениям. */ groups_observed: AnalyticsV2Leader[];
    /** Независимый рейтинг групп по числу наблюдаемых входящих сообщений. */ groups_messages?: AnalyticsV2Leader[];
  };
  /** Первые источники и повторные входы. */
  sources: AnalyticsV2Source[];
  /** Ряд новых пользователей по источникам. */
  source_points: {
    /** Стабильное начало того же UTC-интервала, что и в points. */ date: string;
    /** Исключённый конец того же календарного интервала, что и в points. */ end_date?: string;
    /** Идентичность источника. */ id: string;
    /** Человеческая подпись. */ label: string;
    /** Новые пользователи в интервале. */ new_users: number;
    /** Первые сохранённые контакты с неизвестной фактической первой датой; не входят в точную стоимость привлечения. */ restored_users?: number;
  }[];
  /** Популярность реальных нажатий. */
  buttons: {
    /** Безопасное название кнопки. */ label: string;
    /** Число реальных нажатий с Telegram ID. */ count: number;
    /** Проверенные старые записи, учитываемые как нажатия по принятой методике. */ historical_count?: number;
    /** Уникальные люди, включая аудированные исторические нажатия. */ people?: number;
  }[];
  /** Текущая доступность подтверждённой аудитории. */
  availability: {
    /** Доступны после подтверждённого личного взаимодействия. */ available: number;
    /** Известно о блокировке личного диалога. */ blocked: number;
    /** Профили удалённых аккаунтов. */ deleted: number;
    /** Последняя явная проверка либо отсутствие сведений. */ checked_at: string | null;
  };
  /** Текущие свойства профилей подтверждённой аудитории. */
  composition: {
    /** Профили Telegram Premium. */ premium: number;
    /** Известные обычные профили. */ regular: number;
    /** Нет сохранённых свойств профиля. */ unknown: number;
    /** Распределение языков профилей. */ languages: {
      /** Код языка либо unknown. */ code: string;
      /** Уникальные пользователи языка. */ count: number;
    }[];
  };
  /** Ближайший момент изменения скользящего окна без нового события. */
  next_recompute_at: string | null;
}
